import streamlit as st
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.colors import darkblue
from reportlab.lib.units import inch
from datetime import datetime
import tempfile

st.title("📄 Project Report")

# ----------------------------
# Check Dataset
# ----------------------------
if "df" not in st.session_state:
    st.warning("Please upload a dataset first.")
    st.stop()

df = st.session_state.df

model = st.session_state.get("selected_model", "Not Trained")
accuracy = st.session_state.get("accuracy", "N/A")
target = st.session_state.get("target", "N/A")

rows, cols = df.shape
missing = df.isnull().sum().sum()

st.subheader("Report Summary")

st.write(f"**Rows:** {rows}")
st.write(f"**Columns:** {cols}")
st.write(f"**Missing Values:** {missing}")
st.write(f"**Target Column:** {target}")
st.write(f"**Selected Model:** {model}")
st.write(f"**Accuracy:** {accuracy}%")

# ----------------------------
# Generate PDF
# ----------------------------

if st.button("📄 Generate PDF Report"):

    temp = tempfile.NamedTemporaryFile(delete=False, suffix=".pdf")

    doc = SimpleDocTemplate(temp.name)

    styles = getSampleStyleSheet()

    title = styles["Heading1"]
    title.alignment = TA_CENTER
    title.textColor = darkblue

    heading = styles["Heading2"]
    normal = styles["BodyText"]

    elements = []

    elements.append(Paragraph("📊 DATASENSE AI", title))
    elements.append(Paragraph("Intelligent Data Analytics Platform", normal))
    elements.append(Spacer(1, 0.3 * inch))

    elements.append(Paragraph("DATASET SUMMARY", heading))
    elements.append(Paragraph(f"Rows : {rows}", normal))
    elements.append(Paragraph(f"Columns : {cols}", normal))
    elements.append(Paragraph(f"Missing Values : {missing}", normal))
    elements.append(Spacer(1, 0.2 * inch))

    elements.append(Paragraph("MACHINE LEARNING", heading))
    elements.append(Paragraph(f"Target Column : {target}", normal))
    elements.append(Paragraph(f"Selected Model : {model}", normal))
    elements.append(Paragraph(f"Accuracy : {accuracy}%", normal))
    elements.append(Spacer(1, 0.2 * inch))

    elements.append(Paragraph("REPORT GENERATED", heading))
    elements.append(
        Paragraph(
            datetime.now().strftime("%d-%m-%Y %H:%M:%S"),
            normal
        )
    )

    elements.append(Spacer(1, 0.3 * inch))

    elements.append(
        Paragraph(
            "Generated by DataSense AI",
            normal
        )
    )

    doc.build(elements)

    with open(temp.name, "rb") as pdf:

        st.download_button(
            "⬇ Download PDF Report",
            pdf,
            file_name="DataSense_Report.pdf",
            mime="application/pdf"
        )